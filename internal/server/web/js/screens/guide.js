async function loadSusp() {
  const box = $('#gSusp', root);
  let list;
  try { list = await api('/api/suspensions'); } catch (e) { box.textContent = e.message; return; }
  const adj = (name, a) => a && a.how ? `<div>${name}</div><div><b class="${a.usual ? 'yes' : 'no'}">${a.usual ? 'обычно регулируется' : 'обычно не регулируется'}.</b> ${esc(a.how)}${a.tip ? `<br><span class="muted">${esc(a.tip)}</span>` : ''}</div>` : '';
  box.innerHTML = list.all.filter(s => s.id).map(s => `
    <div class="susp-card">
      <h3>${esc(s.name)} <span class="badge">${{ front: 'передняя', rear: 'задняя', both: 'передняя и задняя' }[s.axle]}</span></h3>
      <p>${esc(s.summary)}</p>
      <p class="muted"><b>Как узнать:</b> ${esc(s.identify)}</p>
      ${s.examples && s.examples.length ? `<p class="muted"><b>Например:</b> ${s.examples.map(esc).join('; ')}</p>` : ''}
      <div class="adj">${adj('Развал', s.camber)}${adj('Кастер', s.caster)}${adj('Схождение', s.toe)}</div>
      <details><summary style="cursor:pointer;color:var(--blue)">Проверить до регулировки</summary>
        <ul class="plain">${s.pre_checks.map(c => `<li>${esc(c)}</li>`).join('')}</ul></details>
      ${s.notes && s.notes.length ? `<ul class="plain muted">${s.notes.map(n => `<li>${esc(n)}</li>`).join('')}</ul>` : ''}
    </div>`).join('');
}
